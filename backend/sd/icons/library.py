WORD_RE = re.compile(r"[а-яёa-z]+", re.IGNORECASE)


def rank(text: str) -> list[str]:
    """Подходящие иконки по убыванию уверенности. Пусто — ничего не подошло."""
    words = [word.lower() for word in WORD_RE.findall(text or "")]
    if not words:
        return []

    scores: dict[str, int] = {}
    earliest: dict[str, int] = {}
    for position, word in enumerate(words):
        for name, stems in KEYWORDS.items():
            if not any(word.startswith(stem) for stem in stems):
                continue
            # Ранние слова важнее: смысл тезиса задаётся началом фразы.
            scores[name] = scores.get(name, 0) + (3 if position < 3 else 1)
            earliest.setdefault(name, position)
    # При равном счёте выигрывает тот смысл, что встретился раньше: он ближе к
    # тому, о чём тезис, а не к его придаточным.
    return sorted(scores, key=lambda name: (-scores[name], earliest[name]))


def pick(text: str) -> str | None:
    """Иконка по смыслу текста. None — если ничего не подошло уверенно."""
    candidates = rank(text)
    return candidates[0] if candidates else None
