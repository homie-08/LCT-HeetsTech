"""Три варианта вёрстки одной презентации: ось различий — плотность.

ТЗ просит показать один и тот же контент на одном шаблоне в трёх вариантах,
визуально различимых и одинаково верных правилам шаблона. Ось выбрана не
случайно. Всё, что в конвейере решает «сколько положить на слайд», уже
выражено числами: сколько тезисов уносит слайд, насколько плотно текст
заполняет слоты, сколько мест в раскладке считается нормой. Плотность —
это те же рычаги с тремя настройками, а не три разных алгоритма.

Правилам шаблона все три подчиняются одинаково: макеты берутся из его же
библиотеки, цвета и шрифты — из его дизайн-системы. Меняется только то, что
меняет и живой дизайнер, когда его просят «покороче» или «повоздушнее»:
число слайдов, число мыслей на слайде и выбор между сеткой карточек и одной
крупной фразой.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Variant:
    id: str
    label: str
    tagline: str
    max_theses: int
    """Сколько тезисов уносит один слайд."""
    dividers: bool
    """Ставить ли разделители перед крупными частями."""
    places_bias: float
    """Предпочтение матчера: > 0 — сетки со многими местами, < 0 — одно крупное."""
    fill_window: tuple[float, float]
    """Заполненность слотов знаками, которая считается хорошей."""
    agenda_items: int
    """Сколько пунктов держит содержание; ноль — содержания нет."""
    stretch: float = 1.0
    """Насколько план модели может вырасти при делении слайдов: 1.5 — на половину.

    Без предела просторная вёрстка на плане из двенадцати слайдов по пять
    тезисов давала тридцать с лишним слайдов — это уже не «повоздушнее»,
    а другая презентация. Делятся в первую очередь самые тяжёлые слайды."""


VARIANTS: dict[str, Variant] = {
    "compact": Variant(
        id="compact", label="Сжато",
        tagline="меньше слайдов, больше мыслей на каждом — для отчёта и рассылки",
        max_theses=6, dividers=False, places_bias=1.0, fill_window=(0.6, 1.0),
        agenda_items=0),
    "balanced": Variant(
        id="balanced", label="Сбалансированно",
        tagline="три-четыре тезиса на слайд — для живого выступления",
        max_theses=4, dividers=False, places_bias=0.0, fill_window=(0.45, 0.95),
        agenda_items=5, stretch=1.2),
    "spacious": Variant(
        id="spacious", label="Просторно",
        tagline="одна-две мысли на слайд и разделители — для сцены и большого зала",
        max_theses=2, dividers=True, places_bias=-1.0, fill_window=(0.3, 0.8),
        agenda_items=4, stretch=1.5),
}
DEFAULT = "balanced"
ORDER = ["compact", "balanced", "spacious"]


def get(name: str | None) -> Variant:
    """Вариант по имени; пустое имя — сбалансированный."""
    key = (name or DEFAULT).strip().lower()
    if key not in VARIANTS:
        raise KeyError(f"неизвестный вариант вёрстки: {name!r}; есть {', '.join(ORDER)}")
    return VARIANTS[key]


def all_variants() -> list[Variant]:
    return [VARIANTS[name] for name in ORDER]
